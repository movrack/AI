#!/usr/bin/env python3
"""Install the agents of this repository into AI assistants (standard library only).

Reads agents/*.md (neutral format) and writes one file per assistant in the
format and place it expects. Never deletes anything; backs up any foreign file
before replacing it.
"""
import argparse
import datetime
import json
import os
import re
import sys
import tempfile
from pathlib import Path

MARKER = "generated by sync_agents.py"
ASSISTANTS = ("claude", "codex", "gemini", "copilot")
CONFIG_DIRS = {"claude": ".claude", "codex": ".codex", "gemini": ".gemini", "copilot": ".copilot"}

TOOL_MAP = {
    "read": {"claude": ["Read"], "gemini": ["read_file", "read_many_files"], "copilot": ["read"]},
    "search": {"claude": ["Grep", "Glob"], "gemini": ["grep_search", "glob", "list_directory"], "copilot": ["search"]},
    "edit": {"claude": ["Edit", "Write"], "gemini": ["replace", "write_file"], "copilot": ["edit"]},
    "execute": {"claude": ["Bash"], "gemini": ["run_shell_command"], "copilot": ["execute"]},
    "web": {"claude": ["WebFetch", "WebSearch"], "gemini": ["web_fetch", "google_web_search"], "copilot": ["web"]},
    "agent": {"claude": ["Agent"], "gemini": [], "copilot": ["agent"]},
}


class AgentError(Exception):
    pass


class Agent:
    def __init__(self, name, description, tools, model, body, source):
        self.name, self.description, self.tools = name, description, tools
        self.model, self.body, self.source = model, body, source


def parse_agent(path):
    text = path.read_text(encoding="utf-8")
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        raise AgentError(f"{path.name}: header must start with a '---' line")
    try:
        end = next(i for i in range(1, len(lines)) if lines[i].strip() == "---")
    except StopIteration:
        raise AgentError(f"{path.name}: header is not closed by a second '---' line")
    fields = {}
    for raw in lines[1:end]:
        if not raw.strip() or raw.lstrip().startswith("#"):
            continue
        if ":" not in raw:
            raise AgentError(f"{path.name}: invalid header line: {raw!r}")
        key, value = raw.split(":", 1)
        key, value = key.strip(), value.strip()
        if key != "description":
            value = re.sub(r"\s+#.*$", "", value)
        fields[key] = value
    name = fields.get("name", "")
    if not name:
        raise AgentError(f"{path.name}: missing 'name' in header")
    if name != path.stem:
        raise AgentError(f"{path.name}: name '{name}' must equal the file name '{path.stem}'")
    if not fields.get("description"):
        raise AgentError(f"{path.name}: missing 'description' in header")
    tools = [t.strip() for t in fields.get("tools", "*").split(",") if t.strip()]
    if not tools or "*" in tools:
        tools = None
    else:
        for t in tools:
            if t not in TOOL_MAP and not re.fullmatch(r"mcp:[^/\s]+/[^/\s]+", t):
                raise AgentError(f"{path.name}: unknown tool '{t}'")
    body = "\n".join(lines[end + 1:]).strip("\n") + "\n"
    return Agent(name, fields["description"], tools, fields.get("model") or None, body, path.name)


def map_tools(tools, assistant):
    if tools is None:
        return None
    out = []
    for t in tools:
        if t.startswith("mcp:"):
            server, tool = t[4:].split("/", 1)
            names = {"claude": [f"mcp__{server}__{tool}"], "gemini": [f"mcp_{server}_{tool}"],
                     "copilot": [f"{server}/{tool}"]}[assistant]
        else:
            names = TOOL_MAP[t][assistant]
        out += [n for n in names if n not in out]
    return out


def note(a):
    return f"{MARKER} from agents/{a.source}; do not edit, re-run the script instead"


def render_claude(a):
    h = ["---", f"name: {a.name}", f"description: {json.dumps(a.description, ensure_ascii=False)}"]
    tools = map_tools(a.tools, "claude")
    if tools:
        h.append("tools: " + ", ".join(tools))
    if a.model:
        h.append(f"model: {a.model}")
    h.append("---")
    return "\n".join(h) + f"\n<!-- {note(a)} -->\n\n" + a.body


def render_copilot(a):
    h = ["---", f"name: {a.name}", f"description: {json.dumps(a.description, ensure_ascii=False)}"]
    tools = map_tools(a.tools, "copilot")
    if tools:
        h.append("tools: " + json.dumps(tools))
    h.append("user-invocable: true")
    h.append("---")
    return "\n".join(h) + f"\n<!-- {note(a)} -->\n\n" + a.body


def render_gemini(a):
    h = ["---", f"name: {a.name}", f"description: {json.dumps(a.description, ensure_ascii=False)}", "kind: local"]
    tools = map_tools(a.tools, "gemini")
    if tools:
        h.append("tools:")
        h += [f"  - {t}" for t in tools]
    if a.model:
        h.append(f"model: {a.model}")
    h.append("---")
    return "\n".join(h) + f"\n<!-- {note(a)} -->\n\n" + a.body


def toml_basic(s):
    return json.dumps(s, ensure_ascii=False)


def render_codex(a):
    body = a.body.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    return (f"# {note(a)}\n"
            f"name = {toml_basic(a.name.replace('-', '_'))}\n"
            f"description = {toml_basic(a.description)}\n"
            f'developer_instructions = """\n{body}"""\n')


def targets(assistant, agent, home, scope, project):
    base = home if scope == "user" else project
    if assistant == "claude":
        return base / ".claude/agents" / f"{agent.name}.md", render_claude
    if assistant == "copilot":
        d = ".copilot/agents" if scope == "user" else ".github/agents"
        return base / d / f"{agent.name}.agent.md", render_copilot
    if assistant == "gemini":
        return base / ".gemini/agents" / f"{agent.name}.md", render_gemini
    return base / ".codex/agents" / f"{agent.name.replace('-', '_')}.toml", render_codex


def is_generated(path):
    try:
        with open(path, "r", encoding="utf-8") as f:
            return MARKER in f.read(4096)
    except (OSError, UnicodeDecodeError):
        return False


def atomic_write(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=".sync_agents_")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write(content)
        os.chmod(tmp, 0o644)
        os.replace(tmp, path)  # replaces a symlink itself, not its target
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise


def backup(path, home, stamp, assistant):
    dest = home / ".config/ai-agents/_backup" / stamp / assistant / path.name
    dest.parent.mkdir(parents=True, exist_ok=True)
    if path.is_symlink():
        link = os.readlink(path)
        if path.exists():
            dest.write_bytes(path.read_bytes())
        (dest.parent / (path.name + ".symlink")).write_text(link + "\n", encoding="utf-8")
    else:
        dest.write_bytes(path.read_bytes())
    return dest


def main(argv=None):
    p = argparse.ArgumentParser(description="Install the repository agents into AI assistants.")
    p.add_argument("--source", help="folder of agent .md files (default: ../../../agents of this script)")
    p.add_argument("--assistants", help="comma list of: " + ",".join(ASSISTANTS) +
                   " (default: those whose config folder exists)")
    p.add_argument("--scope", choices=("user", "project"), default="user")
    p.add_argument("--project", help="project folder (required with --scope project)")
    p.add_argument("--dry-run", action="store_true", help="show what would happen, write nothing")
    p.add_argument("--only", help="comma list of agent names")
    args = p.parse_args(argv)

    home = Path.home()
    source = Path(args.source) if args.source else Path(__file__).resolve().parents[3] / "agents"
    if not source.is_dir():
        print(f"error: source folder not found: {source}", file=sys.stderr)
        return 2
    if args.scope == "project" or args.project:
        if not args.project or not Path(args.project).is_dir():
            print("error: --scope project needs --project PATH (an existing folder)", file=sys.stderr)
            return 2
        args.scope = "project"
    project = Path(args.project) if args.project else None

    if args.assistants:
        chosen = [a.strip() for a in args.assistants.split(",") if a.strip()]
        bad = [a for a in chosen if a not in ASSISTANTS]
        if bad:
            print(f"error: unknown assistant(s): {', '.join(bad)}", file=sys.stderr)
            return 2
    else:
        chosen = [a for a in ASSISTANTS if (home / CONFIG_DIRS[a]).is_dir()]
        if not chosen:
            print("error: no assistant detected (no ~/.claude, ~/.codex, ~/.gemini, ~/.copilot); use --assistants",
                  file=sys.stderr)
            return 2

    files = sorted(source.glob("*.md"))
    only = {n.strip() for n in args.only.split(",")} if args.only else None
    if only:
        missing = only - {f.stem for f in files}
        if missing:
            print(f"error: unknown agent(s): {', '.join(sorted(missing))}", file=sys.stderr)
            return 2
        files = [f for f in files if f.stem in only]
    if not files:
        print(f"error: no agent files in {source}", file=sys.stderr)
        return 2

    agents, errors = [], 0
    for f in files:
        try:
            agents.append(parse_agent(f))
        except AgentError as e:
            print(f"error: {e}", file=sys.stderr)
            errors += 1
    if errors:
        print(f"{errors} invalid agent file(s); nothing written", file=sys.stderr)
        return 1

    stamp = datetime.datetime.now().strftime("%Y%m%d-%H%M%S")
    counts = {"created": 0, "updated": 0, "unchanged": 0, "backup": 0}
    prefix = "[dry-run] " if args.dry_run else ""
    for assistant in chosen:
        for a in agents:
            path, render = targets(assistant, a, home, args.scope, project)
            content = render(a)
            try:
                status, extra = None, ""
                if path.is_symlink() or path.exists():
                    if not path.is_symlink() and path.read_text(encoding="utf-8", errors="replace") == content:
                        status = "unchanged"
                    elif path.is_symlink() or not is_generated(path):
                        status = "backup"
                        extra = f" (previous file saved under {home / '.config/ai-agents/_backup' / stamp})"
                        if not args.dry_run:
                            backup(path, home, stamp, assistant)
                    else:
                        status = "updated"
                else:
                    status = "created"
                if status != "unchanged" and not args.dry_run:
                    atomic_write(path, content)
                counts[status] += 1
                print(f"{prefix}{status:9} {assistant:7} {path}{extra}")
            except OSError as e:
                print(f"error: {assistant} {path}: {e}", file=sys.stderr)
                errors += 1
    print(f"{prefix}summary: {counts['created']} created, {counts['updated']} updated, "
          f"{counts['unchanged']} unchanged, {counts['backup']} backed up and replaced, {errors} error(s)")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
