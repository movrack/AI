import io
import os
import sys
import tempfile
import unittest
from contextlib import redirect_stdout, redirect_stderr
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "scripts"))
import sync_agents  # noqa: E402

REPO_AGENTS = Path(__file__).resolve().parents[3] / "agents"

ALL = """---
name: all-tools
description: Does everything.
tools: *
model: inherit
---
Body with a backslash \\ and a triple quote \"\"\" inside.
"""
MCP = """---
name: browser
description: Uses the browser.
tools: read, search, edit, execute, web, agent, mcp:chrome-devtools/take_screenshot
---
Browse.
"""
QUOTED = """---
name: quoted
# Name: a comment line that must be ignored.
description: Use when: the user says "hello", then reply.
tools: read   # trailing comment
# tools: execute
---
Quoted body.
"""


class SyncTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        root = Path(self.tmp.name)
        self.home = root / "home"
        self.home.mkdir()
        self.src = root / "agents"
        self.src.mkdir()
        for n, t in (("all-tools", ALL), ("browser", MCP), ("quoted", QUOTED)):
            (self.src / f"{n}.md").write_text(t)
        for d in (".claude", ".codex", ".gemini", ".copilot"):
            (self.home / d).mkdir()
        self._old = os.environ.get("HOME")
        os.environ["HOME"] = str(self.home)

    def tearDown(self):
        if self._old is None:
            os.environ.pop("HOME", None)
        else:
            os.environ["HOME"] = self._old
        self.tmp.cleanup()

    def run_main(self, *argv):
        out, err = io.StringIO(), io.StringIO()
        with redirect_stdout(out), redirect_stderr(err):
            code = sync_agents.main(["--source", str(self.src), *argv])
        return code, out.getvalue(), err.getvalue()

    def read(self, rel):
        return (self.home / rel).read_text()

    def test_claude(self):
        self.assertEqual(self.run_main()[0], 0)
        c = self.read(".claude/agents/browser.md")
        self.assertIn("tools: Read, Grep, Glob, Edit, Write, Bash, WebFetch, WebSearch, Agent, "
                      "mcp__chrome-devtools__take_screenshot", c)
        self.assertIn("generated by sync_agents.py", c)
        a = self.read(".claude/agents/all-tools.md")
        self.assertNotIn("tools:", a)
        self.assertIn("model: inherit", a)
        q = self.read(".claude/agents/quoted.md")
        self.assertIn('description: "Use when: the user says \\"hello\\", then reply."', q)
        self.assertIn("tools: Read\n", q)

    def test_copilot_gemini(self):
        self.run_main()
        c = self.read(".copilot/agents/browser.agent.md")
        self.assertIn('tools: ["read", "search", "edit", "execute", "web", "agent", '
                      '"chrome-devtools/take_screenshot"]', c)
        self.assertIn("user-invocable: true", c)
        g = self.read(".gemini/agents/browser.md")
        self.assertIn("kind: local", g)
        self.assertIn("  - read_file\n  - read_many_files\n", g)
        self.assertIn("  - mcp_chrome-devtools_take_screenshot\n", g)
        self.assertNotIn("Agent", g.split("---")[1])

    def test_codex_escaping(self):
        self.run_main()
        t = self.read(".codex/agents/all_tools.toml")
        self.assertIn('name = "all_tools"', t)
        self.assertIn('developer_instructions = """', t)
        self.assertIn("backslash \\\\ and", t)
        self.assertIn('\\"\\"\\" inside', t)
        try:
            import tomllib
        except ImportError:
            return
        data = tomllib.loads(t)
        self.assertIn('triple quote """ inside', data["developer_instructions"])
        self.assertIn("\\ and", data["developer_instructions"])
        tomllib.loads(self.read(".codex/agents/quoted.toml"))

    def test_dry_run_writes_nothing(self):
        code, out, _ = self.run_main("--dry-run")
        self.assertEqual(code, 0)
        self.assertIn("[dry-run] created", out)
        self.assertFalse((self.home / ".claude/agents").exists())
        self.assertFalse((self.home / ".config").exists())

    def test_idempotent(self):
        self.run_main()
        code, out, _ = self.run_main()
        self.assertEqual(code, 0)
        self.assertIn("0 created, 0 updated, 12 unchanged", out)

    def test_updates_generated_file_without_backup(self):
        self.run_main()
        p = self.home / ".claude/agents/quoted.md"
        p.write_text(p.read_text() + "\nmanual edit\n")
        _, out, _ = self.run_main("--assistants", "claude")
        self.assertIn("updated", out)
        self.assertFalse((self.home / ".config/ai-agents/_backup").exists())

    def test_backup_foreign_file(self):
        p = self.home / ".claude/agents/quoted.md"
        p.parent.mkdir()
        p.write_text("my own agent\n")
        _, out, _ = self.run_main("--assistants", "claude")
        self.assertIn("backup", out)
        saved = list((self.home / ".config/ai-agents/_backup").rglob("quoted.md"))
        self.assertEqual(len(saved), 1)
        self.assertEqual(saved[0].read_text(), "my own agent\n")
        self.assertIn("generated by", p.read_text())

    def test_symlink_replaced(self):
        target = Path(self.tmp.name) / "elsewhere.md"
        target.write_text("linked original\n")
        p = self.home / ".claude/agents/quoted.md"
        p.parent.mkdir()
        p.symlink_to(target)
        self.run_main("--assistants", "claude")
        self.assertFalse(p.is_symlink())
        self.assertEqual(target.read_text(), "linked original\n")
        saved = list((self.home / ".config/ai-agents/_backup").rglob("quoted.md"))
        self.assertEqual(saved[0].read_text(), "linked original\n")

    def test_invalid_header(self):
        (self.src / "bad.md").write_text("---\nname: other\ndescription: x\n---\nbody\n")
        code, _, err = self.run_main()
        self.assertEqual(code, 1)
        self.assertIn("must equal the file name", err)
        self.assertFalse((self.home / ".claude/agents").exists())
        (self.src / "bad.md").write_text("no header\n")
        code, _, err = self.run_main()
        self.assertEqual(code, 1)
        self.assertIn("header must start", err)

    def test_only(self):
        _, out, _ = self.run_main("--only", "quoted", "--assistants", "claude")
        self.assertTrue((self.home / ".claude/agents/quoted.md").exists())
        self.assertFalse((self.home / ".claude/agents/browser.md").exists())
        self.assertEqual(self.run_main("--only", "nope")[0], 2)

    def test_project_scope(self):
        proj = Path(self.tmp.name) / "proj"
        proj.mkdir()
        code, _, _ = self.run_main("--scope", "project", "--project", str(proj),
                                   "--assistants", "claude,copilot")
        self.assertEqual(code, 0)
        self.assertTrue((proj / ".claude/agents/browser.md").exists())
        self.assertTrue((proj / ".github/agents/browser.agent.md").exists())
        self.assertFalse((self.home / ".claude/agents").exists())
        self.assertEqual(self.run_main("--scope", "project")[0], 2)

    def test_default_assistants_detected(self):
        import shutil
        shutil.rmtree(self.home / ".codex")
        shutil.rmtree(self.home / ".gemini")
        self.run_main()
        self.assertTrue((self.home / ".claude/agents").exists())
        self.assertFalse((self.home / ".codex").exists())

    def test_real_agents_parse(self):
        if REPO_AGENTS.is_dir():
            for f in REPO_AGENTS.glob("*.md"):
                sync_agents.parse_agent(f)


if __name__ == "__main__":
    unittest.main()
